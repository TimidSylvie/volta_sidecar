static void single(uint8_t a[66], uint8_t b) {
    uint8_t t1 = a[0x40];
    a[t1 + 0x10] = b;
    uint8_t t3 = (uint8_t)((t1 + 1) & 0xf);
    a[t1 + 0x20] = a[t1] ^ b;
    uint8_t t4 = MIX[(uint8_t)(b ^ a[0x41])];
    uint8_t old = a[t1 + 0x30];
    a[t1 + 0x30] = t4 ^ old;
    a[0x41] = t4 ^ old;
    a[0x40] = t3;
    if (t3) return;
    uint8_t x = 0x29, k = 0;
    for (;;) {
        x ^= a[0]; a[0] = x;
        for (int i = 1; i < 0x30; i++) { x = a[i] ^ MIX[x]; a[i] = x; }
        x = (uint8_t)(x + k);
        if (++k == 0x12) break;
        x = MIX[x];
    }
}
static void hash_pass(uint8_t a[66], const void *p, size_t n, uint8_t mask) {
    for (size_t i = 0; i < n; i++) single(a, ((const uint8_t *)p)[i] ^ mask);
}
static void pass5(uint8_t a[66], uint64_t out[2]) {
    uint8_t t = (uint8_t)(16 - a[64]);
    for (uint8_t i = 0; i < t; i++) single(a, t);
    for (int i = 0x30; i < 0x40; i++) single(a, a[i]);   /* Each step reads the byte changed by the one before it. */
    memcpy(out, a, 16);
}

struct sc_ic_input {               /* The layout itself is hashed byte for byte. */
    uint32_t driver_version, version, process, thread;
    const void *cudart_table, *integrity_table, *fn_address;
    uint64_t unix_seconds;
};
struct sc_ic_device { unsigned char uuid[16]; int32_t pci_domain, pci_bus, pci_device; };

void sc_integrity_hash(const struct sc_ic_input *in, const struct sc_ic_device *dev, unsigned ndev, uint64_t out[2]) {
    if (in->version % 10 == 0) { out[0] = 0x3341181C03CB675CULL; out[1] = 0x8ED383AA1F4CD1E8ULL; return; }
    if (in->version % 10 == 1) { out[0] = 0x1841181C03CB675CULL; out[1] = 0x8ED383AA1F4CD1E8ULL; return; }
    static const uint8_t p1[16] = {0x14,0x6A,0xDD,0xAE,0x53,0xA9,0xA7,0x52,0xAA,0x08,0x41,0x36,0x0B,0xF5,0x5A,0x9F};
    uint8_t a[66] = {0};
    uint64_t r1[2];
    hash_pass(a, p1, 16, 0x36);
    hash_pass(a, in, sizeof *in, 0);
    for (unsigned d = 0; d < ndev; d++) hash_pass(a, &dev[d], sizeof dev[d], 0);
    pass5(a, r1);
    memset(a, 0, 16); memset(a + 48, 0, 18);
    hash_pass(a, p1, 16, 0x5c);
    hash_pass(a, r1, 16, 0);
    pass5(a, out);
}
