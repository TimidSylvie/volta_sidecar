#!/usr/bin/env python3
"""Generate a routing trampoline for every function exported by the real NVML.

Usage: gen_proxy.py REAL_LIBNVIDIA_ML OUT_DIR
Writes OUT_DIR/names.c (the exported names, index order) and OUT_DIR/stubs.S (one trampoline per name that
nvml_proxy.c does not implement itself). A trampoline saves every argument register, asks sc_route(arg1, index)
for the real function (host or legacy copy), restores the registers and jumps there - so no signature is needed.
"""
import pathlib
import re
import subprocess
import sys

real, out = sys.argv[1], pathlib.Path(sys.argv[2])
here = pathlib.Path(__file__).resolve().parent
names = sorted(l.split()[2] for l in subprocess.run(["nm", "-D", "--defined-only", real], capture_output=True,
                                                     text=True, check=True).stdout.splitlines()
               if len(l.split()) == 3 and l.split()[1] == "T")
if not names:
    sys.exit(f"no exported functions found in {real}")
# The routing core implements calls that need merged enumeration or more than one handle.
src = (here / "nvml_proxy.c").read_text()
special = set(re.findall(r"^nvmlReturn_t (nvml\w+)\(", src, re.M))
special |= set(re.findall(r"^LOOKUP\((nvml\w+),", src, re.M))
special |= set(re.findall(r"^PAIR\((nvml\w+),", src, re.M))

out.mkdir(parents=True, exist_ok=True)
(out / "names.c").write_text(
    "/* generated by gen_proxy.py */\nconst char *const sc_names[] = {\n"
    + "".join(f'    "{n}",\n' for n in names) + "};\nconst int sc_count = %d;\n" % len(names))

stub = """    .globl {name}
    .type {name}, @function
{name}:
    pushq %rdi
    pushq %rsi
    pushq %rdx
    pushq %rcx
    pushq %r8
    pushq %r9
    subq $136, %rsp
    movdqu %xmm0, 0(%rsp)
    movdqu %xmm1, 16(%rsp)
    movdqu %xmm2, 32(%rsp)
    movdqu %xmm3, 48(%rsp)
    movdqu %xmm4, 64(%rsp)
    movdqu %xmm5, 80(%rsp)
    movdqu %xmm6, 96(%rsp)
    movdqu %xmm7, 112(%rsp)
    movl ${idx}, %esi
    call sc_route@PLT
    movdqu 0(%rsp), %xmm0
    movdqu 16(%rsp), %xmm1
    movdqu 32(%rsp), %xmm2
    movdqu 48(%rsp), %xmm3
    movdqu 64(%rsp), %xmm4
    movdqu 80(%rsp), %xmm5
    movdqu 96(%rsp), %xmm6
    movdqu 112(%rsp), %xmm7
    addq $136, %rsp
    popq %r9
    popq %r8
    popq %rcx
    popq %rdx
    popq %rsi
    popq %rdi
    jmp *%rax
    .size {name}, .-{name}
"""
body = "".join(stub.format(name=n, idx=i) for i, n in enumerate(names) if n not in special)
(out / "stubs.S").write_text("/* generated by gen_proxy.py */\n    .text\n" + body + '    .section .note.GNU-stack,"",@progbits\n')
print(f"{len(names)} exported functions: {len(names) - len(special & set(names))} trampolines, "
      f"{len(special & set(names))} implemented in nvml_proxy.c")
missing = special - set(names)
if missing:
    print("note: not exported by this NVML (fine):", " ".join(sorted(missing)))
